#!/usr/bin/env python3
"""Read-aloud recordings - Kokoro TTS (free, open-source, runs locally).

Records every text of tools/read-audio/texts.json (made by harvest.js: the
questions, choices, answers and explanations of grammar, vocabulary, idioms...
and the Listen buttons of the lessons) with the Kokoro voice am_michael, speed
1.0, as assets/audio/read/<hash>.mp3, the name the website computes from the
text (assets/listen-audio.js, hash()). Only MISSING texts are recorded.

  python3 tools/read-audio/generate.py                       # count only
  python3 tools/read-audio/generate.py --all [--shard 0 --shards 8] [--out DIR]
  python3 tools/read-audio/generate.py --index               # write index.js, remove unused files

Needs: pip install "kokoro>=0.9.4" soundfile; espeak-ng and ffmpeg.
"""
import argparse, glob, json, os, re, subprocess, sys, tempfile, time

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
TEXTS = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'texts.json')
OUT = os.path.join(ROOT, 'assets', 'audio', 'read')
INDEX = os.path.join(OUT, 'index.js')
MODEL = 'hexgrad/Kokoro-82M'
VOICE = 'am_michael'
SPEED = 1.0
SR = 24000
BITRATE = '48k'
BLANK_S = 0.4                   # a blank (_____) is a short silence, as with the browser voices
# Kokoro leaves ~0.4 s of silence before and ~0.5 s after the voice: the clips are
# played one after the other ("A." then the choice), so only 0.06 s / 0.12 s are kept
TRIM = ('silenceremove=start_periods=1:start_threshold=-50dB:start_silence=0.06,areverse,'
        'silenceremove=start_periods=1:start_threshold=-50dB:start_silence=0.12,areverse')
# choice letters, said as letter names (Kokoro / misaki phonemes)
LETTERS = {'A.': '[A](/ˈA/).', 'B.': '[B](/bˈi/).', 'C.': '[C](/sˈi/).',
           'D.': '[D](/dˈi/).', 'E.': '[E](/ˈi/).', 'F.': '[F](/ˈɛf/).'}


def load():
    # a text with no letter or digit ("-") has nothing to say: the browser voice keeps it
    return [x for x in json.load(open(TEXTS, encoding='utf-8'))['items'] if re.search(r'[A-Za-z0-9]', x['t'])]


def segments(text):
    """Text given to Kokoro, cut at the blanks (each blank becomes a silence)."""
    if text in LETTERS:
        return [LETTERS[text]]
    t = re.sub(r'[‘’]', "'", text)
    t = re.sub(r'[“”]', '"', t)
    t = re.sub(r'\s*(?:->|→)\s*', ', ', t)
    t = re.sub(r'(?<=[A-Za-z])/(?=[A-Za-z])', ' or ', t)
    t = re.sub(r'[–—]', ', ', t)
    parts = re.split(r'_{2,}|…+|\.{3,}', t)
    return [re.sub(r'\s+', ' ', p).strip(' ,') for p in parts] if len(parts) > 1 else [re.sub(r'\s+', ' ', t).strip()]


class Kokoro:
    def __init__(self):
        import numpy as np, soundfile as sf
        from kokoro import KPipeline
        self.np, self.sf = np, sf
        self.pipe = KPipeline(lang_code='a', repo_id=MODEL)          # 'a' = American English

    def say(self, text):
        out = [r.audio.cpu().numpy().astype('float32') for r in self.pipe(text, voice=VOICE, speed=SPEED, split_pattern=r'\n+')
               if r.audio is not None]
        return self.np.concatenate(out) if out else None

    def mp3(self, text, dest):
        np, gap, pieces = self.np, self.np.zeros(int(SR * BLANK_S), dtype='float32'), []
        segs = segments(text)
        for k, s in enumerate(segs):
            if k:
                pieces.append(gap)
            if re.search(r'[A-Za-z0-9]', s):
                a = self.say(s)
                if a is not None:
                    pieces.append(a)
        if not pieces or not any(len(p) for p in pieces if p is not gap):
            return False
        with tempfile.NamedTemporaryFile(suffix='.wav', delete=False) as w:
            self.sf.write(w.name, np.concatenate(pieces), SR)
        try:
            subprocess.run(['ffmpeg', '-loglevel', 'error', '-y', '-i', w.name,
                            '-af', TRIM + ',loudnorm=I=-16:TP=-1.5:LRA=11', '-ac', '1', '-ar', str(SR),
                            '-codec:a', 'libmp3lame', '-b:a', BITRATE, '-map_metadata', '-1', '-id3v2_version', '0',
                            dest], check=True)
        finally:
            os.unlink(w.name)
        return True


def write_index(items):
    have = {os.path.basename(p)[:-4] for p in glob.glob(os.path.join(OUT, '*.mp3'))}
    want = {x['h'] for x in items}
    for h in have - want:                                   # texts no longer read anywhere
        os.unlink(os.path.join(OUT, h + '.mp3'))
    n = len(have & want)
    with open(INDEX, 'w', encoding='utf-8') as f:
        f.write('/* Read-aloud recordings (Kokoro TTS, am_michael, speed 1.0). Generated by tools/read-audio/generate.py. */\n'
                'window.ECL_READ_AUDIO = ' + json.dumps({'v': 1, 'voice': VOICE, 'speed': SPEED, 'count': n}) + ';\n')
    mp3 = glob.glob(os.path.join(OUT, '*.mp3'))
    print('index.js: %d of %d texts recorded, %d removed, %.1f MB' % (n, len(want), len(have - want), sum(map(os.path.getsize, mp3)) / 1e6))


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--all', action='store_true', help='record every missing text')
    ap.add_argument('--shard', type=int, default=0)
    ap.add_argument('--shards', type=int, default=1)
    ap.add_argument('--out', default=OUT, help='folder for the new files (default assets/audio/read)')
    ap.add_argument('--index', action='store_true', help='write index.js and remove unused recordings')
    ap.add_argument('--missing', action='store_true', help='print the number of missing recordings')
    a = ap.parse_args()

    items = load()
    if a.missing:
        print(sum(1 for x in items if not os.path.exists(os.path.join(OUT, x['h'] + '.mp3'))))
        return
    if a.index:
        write_index(items)
        return
    missing = [x for x in items if not os.path.exists(os.path.join(OUT, x['h'] + '.mp3'))]
    chars = sum(len(x['t']) for x in items)
    print('Texts: %d (%d characters, about %.1f hours); recorded: %d; missing: %d' % (
        len(items), chars, chars / 14.5 / 3600, len(items) - len(missing), len(missing)))
    if not a.all:
        print('Count only. Use --all to record.')
        return
    todo = [x for k, x in enumerate(missing) if k % a.shards == a.shard]
    print('Shard %d/%d: %d texts, %d characters' % (a.shard, a.shards, len(todo), sum(len(x['t']) for x in todo)), flush=True)
    if not todo:
        return
    os.makedirs(a.out, exist_ok=True)
    tts, t0, bad = Kokoro(), time.time(), 0
    for n, x in enumerate(todo, 1):
        if not tts.mp3(x['t'], os.path.join(a.out, x['h'] + '.mp3')):
            bad += 1
            print('  no audio for: %r' % x['t'][:80])
        if n % 100 == 0 or n == len(todo):
            print('  %d/%d done (%.0f s)' % (n, len(todo), time.time() - t0), flush=True)
    print('Shard %d: %d recorded, %d without audio.' % (a.shard, len(todo) - bad, bad))


if __name__ == '__main__':
    main()
